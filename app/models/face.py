import datetime
import uuid
from typing import TYPE_CHECKING, Any, Dict, Optional
from pgvector.sqlalchemy import Vector
from sqlalchemy import JSON, DateTime, Float, ForeignKey, Index, func
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.models.base import Base, GUID

if TYPE_CHECKING:
    from app.models.event import Event
    from app.models.photo import Photo


class PhotoFace(Base):
    __tablename__ = "photo_faces"

    id: Mapped[uuid.UUID] = mapped_column(
        GUID,
        primary_key=True,
        default=uuid.uuid4,
    )
    event_id: Mapped[uuid.UUID] = mapped_column(
        GUID,
        ForeignKey("events.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    photo_id: Mapped[uuid.UUID] = mapped_column(
        GUID,
        ForeignKey("photos.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    # 128-dimensional L2-normalized face embedding generated by OpenCV SFace
    embedding = mapped_column(Vector(128), nullable=False)
    bounding_box: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    detection_confidence: Mapped[float] = mapped_column(Float, nullable=False)
    landmarks: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)
    created_at: Mapped[datetime.datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # Relationships
    event: Mapped["Event"] = relationship("Event", back_populates="faces")
    photo: Mapped["Photo"] = relationship("Photo", back_populates="faces")


# Event-scoped index for vector similarity searches
Index("idx_photo_faces_event_photo", PhotoFace.event_id, PhotoFace.photo_id)

